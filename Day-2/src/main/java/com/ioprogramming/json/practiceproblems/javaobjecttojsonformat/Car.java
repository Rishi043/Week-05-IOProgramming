package com.ioprogramming.json.practiceproblems.javaobjecttojsonformat;

public class Car {
    String brand;
    String name;
    String color;

    // Constructor
    public Car(String brand, String name, String color) {
        this.brand = brand;
        this.name = name;
        this.color = color;
    }

    public String getBrand() {
        return brand;
    }

    public String getName() {
        return name;
    }

    public String getColor() {
        return color;
    }
}

